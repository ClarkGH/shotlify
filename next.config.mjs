// @ts-check
/**
 * Run `build` or `dev` with `SKIP_ENV_VALIDATION` to skip env validation.
 * This is especially useful for Docker builds.
 */
!process.env.SKIP_ENV_VALIDATION && (await import("./src/env/server.mjs"));

/* Content Security Policy. Production only: dev's hot reload needs eval.
 * Builds use webpack (see package.json) because its pages-router output has
 * no inline scripts, so 'self' works without nonces and pages stay static.
 * Frames and uploads are data: URLs, so img and media allow data: and blob:.
 * Slice 5 adds the render API origin to connect-src and media-src. */
const contentSecurityPolicy = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data: blob:",
  "media-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

/** @type {import("next").NextConfig} */
const config = {
  async headers() {
    if (process.env.NODE_ENV !== "production") return [];
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: contentSecurityPolicy },
        ],
      },
    ];
  },
  reactStrictMode: true,
  /* If trying out the experimental appDir, comment the i18n config out
   * @see https://github.com/vercel/next.js/issues/41980 */
  i18n: {
    locales: ["en"],
    defaultLocale: "en",
  },
  /* Images are the user's own data and blob URLs, so the optimizer has
   * nothing to do. Turning it off makes /_next/image return 404. */
  images: {
    unoptimized: true,
  },
};
export default config;
